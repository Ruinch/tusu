import { UniversityProgram } from '../types';

export function getAdmissionRoute(uni: UniversityProgram) {
  const route = uni.admissionRoute ?? (uni.country === 'kz' ? 'kz_grant' : 'international_direct');

  switch (route) {
    case 'nu_internal':
      return {
        title: 'Внутренний конкурс NU',
        steps: 'Заявка подаётся в личном кабинете NU. Нужны документы и международный языковой тест; путь поступления зависит от категории абитуриента. ЕНТ не заменяет внутренний конкурс NU.',
        disclaimer: 'Минимальные баллы — допуск к конкурсу, а не гарантия зачисления.'
      };
    case 'kz_direct':
      return {
        title: 'Прямое платное поступление в вуз',
        steps: 'Подайте документы в приёмную комиссию выбранного вуза. Учитываются ЕНТ и внутренние условия программы.',
        disclaimer: 'Порог ЕНТ не равен проходному баллу на грант.'
      };
    case 'kz_grant':
      return {
        title: 'Конкурс государственных грантов РК',
        steps: 'Сначала сдаётся основное ЕНТ, затем подаётся заявление на государственный конкурс через eGov или приёмную комиссию. В заявлении выбираются группы программ и вузы.',
        disclaimer: 'Указанный балл — ориентир/минимум. Реальный проходной меняется ежегодно по конкурсу и группе программ.'
      };
    case 'military_service':
      return {
        title: 'Поступление в военный институт МО РК',
        steps: 'Заявление подаётся через eGov. Помимо ЕНТ проходят медицинское освидетельствование, профессионально‑психологический отбор и проверку физической подготовки.',
        disclaimer: 'Есть отдельные требования к гражданству, возрасту, здоровью и полу. Обучение и дальнейшая служба регулируются правилами Министерства обороны.'
      };
    default:
      return {
        title: 'Прямая международная заявка',
        steps: 'Заявка подаётся в собственный портал университета; требования зависят от программы, страны, тестов и пакета документов.',
        disclaimer: 'Минимальные требования не отражают вероятность оффера или стипендии.'
      };
  }
}
